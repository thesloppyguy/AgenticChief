"""Scorecard exports (Excel and CSV). Built from the same scorecard the dashboard shows, so the numbers
cannot differ."""
from __future__ import annotations

import csv
import io
from datetime import UTC, datetime

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill
from sqlalchemy.orm import Session

from app.core.security import Principal
from app.kpi_registry.seed import PILLAR_LABELS, PILLAR_WEIGHTS
from app.services import scorecard as sc

STATUS_FILL = {"green": "C6EFCE", "amber": "FFEB9C", "red": "FFC7CE"}
REASON = {"missing": "No value", "not_due": "Not yet due", "no_source": "No source"}


def safe(v):
    """Neutralize spreadsheet formula injection: a text cell starting with = + - @ (or a tab/CR) is
    prefixed with an apostrophe so Excel and Sheets show it as text."""
    if isinstance(v, str) and v[:1] in ("=", "+", "-", "@", "\t", "\r"):
        return "'" + v
    return v


def _num(x, digits=2):
    return None if x is None else round(x, digits)


def _status_text(o: dict) -> str | None:
    return o["status"] or ("Low coverage" if o.get("status_withheld") else None)


def collect(db: Session, who: Principal, period: str) -> dict:
    card = sc.build_scorecard(db, who, period)
    drill = {p: sc.build_pillar_drilldown(db, who, p, period) for p in PILLAR_WEIGHTS}
    return {"card": card, "drill": drill}


def kpi_rows(data: dict) -> list[list]:
    """One row per company per KPI: achievement, target, score, or why it was excluded."""
    reasons, score_of = {}, {}
    for c in data["card"]["companies"]:
        for p in c["pillars"]:
            for k in p["kpis"]:
                reasons[(c["code"], k["key"])], score_of[(c["code"], k["key"])] = k["excluded_reason"], k["score"]
    rows = []
    for pillar, d in data["drill"].items():
        for k in d["kpis"]:
            for ic in k["companies"]:
                key = (ic["code"], k["key"])
                rows.append([ic["code"], PILLAR_LABELS[pillar], k["key"].replace("_", " ").title(), _num(ic["achievement"], 4),
                             _num(k["target"], 4), _num(score_of.get(key)), REASON.get(reasons.get(key) or "", None)])
    return rows


def to_xlsx(data: dict, who: Principal, period: str) -> bytes:
    card = data["card"]
    wb = Workbook()
    bold = Font(bold=True)

    ws = wb.active
    ws.title = "Scorecard"
    head = ["Company", "Name", "Overall", "Status", "Coverage %", *[PILLAR_LABELS[p] for p in PILLAR_WEIGHTS]]
    ws.append(head)
    for cell in ws[1]:
        cell.font = bold
    g = card["group"]
    ws.append(["GROUP", f"{g['companies_with_data']} of {g['companies_in_scope']} companies with data", _num(g["score"]),
               _status_text(g), round(g["pillar_coverage"] * 100), *[_num(p["score"]) for p in g["pillars"]]])
    for cell in ws[2]:
        cell.font = bold
    for c in card["companies"]:
        ws.append([safe(c["code"]), safe(c["name"]), _num(c["score"]), _status_text(c), round(c["pillar_coverage"] * 100),
                   *[_num(p["score"]) for p in c["pillars"]]])
        fill = STATUS_FILL.get(c["status"] or "")
        if fill:
            ws.cell(ws.max_row, 4).fill = PatternFill("solid", fgColor=fill)
    ws.freeze_panes = "C3"
    ws.column_dimensions["B"].width = 30
    ws.column_dimensions["D"].width = 16

    ws = wb.create_sheet("KPIs")
    ws.append(["Company", "Pillar", "KPI", "Achievement", "Target", "Score", "Excluded because"])
    for cell in ws[1]:
        cell.font = bold
    for r in kpi_rows(data):
        ws.append([safe(v) for v in r])
    ws.freeze_panes = "A2"

    ws = wb.create_sheet("Group")
    ws.append(["Pillar", "KPI", "Weight in pillar %", "Target", "Group achievement", "Group score", "Companies with a value", "Note"])
    for cell in ws[1]:
        cell.font = bold
    for pillar, d in data["drill"].items():
        for k in d["kpis"]:
            note = "No source" if k["no_source"] else REASON.get(k["group_excluded_reason"] or "", None)
            ws.append([PILLAR_LABELS[pillar], k["key"].replace("_", " ").title(), round(k["weight"] * 100), _num(k["target"], 4),
                       _num(k["group_achievement"], 4), _num(k["group_score"]), k["coverage"], note])

    ws = wb.create_sheet("Notes")
    t = card["thresholds"]
    notes = [("Period", period), ("Scoring rules version", card["calc_version"]),
             ("Status thresholds", f"Green from {t['green_min']:g}, amber from {t['amber_min']:g}"),
             ("Scope", "Group (all companies)" if card["scope"] == "group" else "Restricted to the companies you can see"),
             ("Generated", datetime.now(UTC).isoformat(timespec="seconds")), ("Generated by", who.user_id),
             ("KPIs with no source", ", ".join(card["no_source_kpis"]) or "none")]
    if card["synthetic_data"]:
        notes.insert(0, ("WARNING", "This workbook contains synthetic (stub or seed) data. Do not use it for decisions."))
    for k, v in notes:
        ws.append([k, safe(v)])
        ws.cell(ws.max_row, 1).font = bold
    ws.column_dimensions["A"].width = 26
    ws.column_dimensions["B"].width = 90

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def to_csv(data: dict) -> str:
    out = io.StringIO()
    w = csv.writer(out)
    w.writerow(["Company", "Pillar", "KPI", "Achievement", "Target", "Score", "Excluded because"])
    for r in kpi_rows(data):
        w.writerow([safe(v) for v in r])
    return out.getvalue()
