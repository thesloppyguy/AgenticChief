import os
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field, SecretStr
from pydantic_settings import BaseSettings, SettingsConfigDict

# The database lives in backend/data/ by default, whatever directory the process starts from.
DATA_DIR = Path(__file__).resolve().parents[2] / "data"


class IntegrationConfig(BaseModel):
    """One source system. Off unless explicitly enabled, e.g. INTEGRATIONS__SUCCESSFACTORS__ENABLED=true."""

    enabled: bool = False
    base_url: str = ""
    auth: Literal["bearer", "basic", "client_credentials"] = "bearer"
    token: SecretStr | None = None  # auth=bearer
    username: str | None = None  # auth=basic
    password: SecretStr | None = None
    token_url: str | None = None  # auth=client_credentials
    client_id: str | None = None
    client_secret: SecretStr | None = None
    mapping_file: str | None = None  # KPI -> endpoint/field mapping (JSON); unmapped KPIs have no source
    timeout_s: float = 30.0


class Settings(BaseSettings):
    # CHRO_ENV_FILE lets tests (and odd deployments) point somewhere else; the default is backend/.env.
    model_config = SettingsConfigDict(env_file=os.environ.get("CHRO_ENV_FILE", ".env"), extra="ignore",
                                      env_nested_delimiter="__")

    database_url: str = f"sqlite:///{DATA_DIR / 'chro.db'}"
    jwt_secret: str = "dev-secret-change-me-dev-secret-change-me"
    jwt_algorithm: str = "HS256"
    cors_origins: list[str] = ["http://localhost:3000"]
    anthropic_api_key: str | None = None
    default_model: str = "claude-sonnet-5-5"
    routing_model: str = "claude-haiku-5-5"
    deep_reasoning_model: str = "claude-opus-5-5"  # used by agents configured for "deep" reasoning

    # Ingestion. A source's live adapter is used only when its flag is on; otherwise stub data
    # (if enabled); otherwise the source is disabled and its KPIs have no data.
    # Approvals: more targets than this in one action is "bulk" and denied by default.
    approval_bulk_max_targets: int = 5
    approval_allow_self_approval: bool = False  # four-eyes: an approver may not approve their own request

    memory_retention_days: int = 90  # Copilot memories expire after this long unless pinned
    memory_max_per_user: int = 200
    scheduler_enabled: bool = True  # runs scheduled jobs in this process; single instance, like the database
    scheduler_poll_s: float = 30.0
    scheduler_claim_timeout_s: int = 1800  # a claim older than this was left by a crashed run
    workflow_stale_after_s: int = 300  # a 'running' workflow with no heartbeat for this long is interrupted

    # Mock source systems: HTTP endpoints, served by this app, that stand in for SuccessFactors, PeopleStrong,
    # MyHealth and Hi5Plus. Their data is generated by Claude (see app/mock_sources). OFF unless enabled.
    mock_sources_enabled: bool = False
    mock_source_token: SecretStr | None = None  # the bearer token the mock endpoints require
    mock_source_model: str | None = None  # defaults to stub_generator_model
    mock_sources_allow_fallback: bool = False  # if the AI call fails: False = answer 503, True = use seeded data

    stub_data_enabled: bool = True
    stub_data_path: str = "stub_data/stub_company_data.json"
    stub_generator_model: str = "claude-opus-5-5"
    integrations: dict[str, IntegrationConfig] = Field(default_factory=dict)

    # OpenExecutive-style agents / skills / MCP
    specialist_effort: Literal["low", "medium", "high", "xhigh", "max"] = "low"
    company_dir: str = str(DATA_DIR.parent / "company")
    vector_store_path: str = str(DATA_DIR / "chroma")
    mcp_enabled: bool = False
    mcp_servers_path: str = str(DATA_DIR.parent / "company" / "mcp_servers.json")
    mcp_tool_timeout_s: float = 120.0
    mcp_client_actions: bool = False

    # Web search (Anthropic native server tool)
    enable_web_search: bool = False
    web_search_max_uses: int = 2
    web_search_allowed_domains: list[str] = Field(default_factory=list)
    web_search_blocked_domains: list[str] = Field(default_factory=list)

    user_timezone: str = "UTC"
    morning_brief_hour: int = 8
    eod_digest_hour: int = 18
    history_retention_days: int = 90
    reminder_max_pending: int = 25

    def integration(self, source: str) -> IntegrationConfig:
        return self.integrations.get(source, IntegrationConfig())

    @property
    def company_profile_path(self):
        from pathlib import Path

        return Path(self.company_dir) / "profile.yaml"

    @property
    def company_skills_path(self):
        from pathlib import Path

        return Path(self.company_dir) / "skills"


settings = Settings()
