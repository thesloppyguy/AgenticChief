def test_scoped_users_get_only_their_own_companies(client, data):
    wb = workbook(client, headers=h("sam", Role.VIEWER, [1]))
    assert [r[0] for r in wb["Scorecard"].iter_rows(min_row=3, values_only=True)] == ["IC1"]
    assert {r[0] for r in wb["KPIs"].iter_rows(min_row=2, values_only=True)} == {"IC1"}
    assert dict(wb["Notes"].iter_rows(values_only=True))["Scope"].startswith("Restricted")
    csv_text = client.get("/reports/export/scorecard.csv", params={"period": P}, headers=h("sam", Role.VIEWER, [1])).text
    assert {r["Company"] for r in csv.DictReader(io.StringIO(csv_text))} == {"IC1"}


