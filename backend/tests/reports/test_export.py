@pytest.mark.parametrize("value,expected", [("=HYPERLINK(\"http://evil\",\"x\")", "'=HYPERLINK(\"http://evil\",\"x\")"),
                                            ("+1+1", "'+1+1"), ("-2+3", "'-2+3"), ("@SUM(A1)", "'@SUM(A1)"), ("\tcmd", "'\tcmd"),
                                            ("Independent Company 5", "Independent Company 5"), (5, 5), (None, None)])
def test_spreadsheet_formula_injection_is_neutralized(value, expected):
    assert safe(value) == expected


def test_a_hostile_company_name_is_exported_as_text_not_a_formula(client, data):
    data.get(Company, 1).name = '=HYPERLINK("http://evil.example","click")'
    data.commit()
    ws = workbook(client)["Scorecard"]
    cell = ws.cell(3, 2)
    assert cell.value.startswith("'=") and cell.data_type == "s"                                         # stored as a string, not "f"
    assert "=HYPERLINK" not in {c.value for c in ws[3] if c.data_type == "f"}


