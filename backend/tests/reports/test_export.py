P = "2026-10"


def h(user, role=Role.VIEWER, companies=None):
    return {"Authorization": f"Bearer {make_token(user, role, companies)}"}


ADMIN, VIEWER = h("alice", Role.ADMIN), h("vic")


@pytest.fixture()
def data(client):
    db = next(app.dependency_overrides[get_db]())
    ingest(db, P, {s: StubExtractor(s) for s in SOURCE_KPIS})
    yield db
    db.close()


def workbook(client, headers=ADMIN, **params):
    r = client.get("/reports/export/scorecard.xlsx", params={"period": P, **params}, headers=headers)
    assert r.status_code == 200, r.text
    assert r.headers["content-type"].startswith("application/vnd.openxmlformats")
    assert r.headers["content-disposition"] == f'attachment; filename="group-hr-scorecard-{P}.xlsx"'
    return load_workbook(io.BytesIO(r.content))


def test_the_workbook_has_the_four_sheets_and_matches_the_dashboard(client, data):
    wb = workbook(client)
    assert wb.sheetnames == ["Scorecard", "KPIs", "Group", "Notes"]
    api = client.get("/scorecard", params={"period": P}, headers=ADMIN).json()
    ws = wb["Scorecard"]
    rows = list(ws.iter_rows(values_only=True))
    assert rows[0][:5] == ("Company", "Name", "Overall", "Status", "Coverage %") and "Learning & Development" in rows[0]
    assert rows[1][0] == "GROUP" and rows[1][2] == pytest.approx(api["group"]["score"], abs=0.01)
    assert [r[0] for r in rows[2:]] == ["IC1", "IC2", "IC3"]
    for row, c in zip(rows[2:], api["companies"], strict=True):
        assert row[2] == pytest.approx(c["score"], abs=0.01) and row[3] == c["status"]                 # same numbers, not recomputed
        assert row[5:] == tuple(pytest.approx(p["score"], abs=0.01) if p["score"] is not None else None for p in c["pillars"])


def test_the_kpi_and_group_sheets_carry_targets_scores_and_reasons(client, data):
    wb = workbook(client)
    kpis = list(wb["KPIs"].iter_rows(values_only=True))
    assert kpis[0] == ("Company", "Pillar", "KPI", "Achievement", "Target", "Score", "Excluded because")
    assert len(kpis) - 1 == 3 * 23                                                                    # every company x every KPI
    mid = next(r for r in kpis if r[2] == "Mid Term Review" and r[0] == "IC1")
    assert mid[5] is None and mid[6] == "Not yet due"                                                  # October: not due until December
    gptw = next(r for r in kpis if r[2] == "Gptw Score" and r[0] == "IC1")
    assert gptw[5] is None and gptw[6] == "No value"                                                   # a manual KPI nobody entered
    kra = next(r for r in kpis if r[2] == "Kra Submission" and r[0] == "IC1")
    assert kra[4] == 100 and kra[5] is not None and kra[6] is None
    group = list(wb["Group"].iter_rows(values_only=True))
    assert len(group) - 1 == 23 and group[0][0] == "Pillar"
    assert any(r[1] == "Cost Per Hire" and r[7] == "No value" for r in group)


